"""rxptalents.py -- RestedXP's classic talent guides -> ZugzugLeveler/data/Talents.lua

    python -I tools/rxptalents.py <RXPGuides clone> [--out ZugzugLeveler/data/Talents.lua]

RestedXP Guides (https://github.com/RestedXP/RXPGuides, CC BY-NC-SA 4.0) load
Guides/Talents/classic.xml on Forever too (RXPGuides.toc: AllowLoadGameType
vanilla,camelot). The format, from Guides/Talents/README.md: a guide is
#name, #minLevel, #maxLevel, #hardcore, #order, #next, then one `level` block
per level from #minLevel, each with `.talent TAB,ROW,COLUMN,RANK` lines.
Pet talents (.pettalent) are left out.
Output: ns.TalentData[CLASS] = { { name, min, max, hc, order, picks = { { lvl, tab, row, col, rank, note } } } }
"""
import argparse
import os
import re
import subprocess

CLASSES = ["druid", "hunter", "mage", "paladin", "priest", "rogue", "shaman", "warlock", "warrior"]


def lua(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    return '"' + str(v).replace("\\", "\\\\").replace('"', '\\"') + '"'


def parse(text):
    guides = []
    for body in re.findall(r"RegisterGuide\(\[\[(.*?)\]\]", text, re.S):
        g = {"name": None, "min": 10, "max": 60, "hc": False, "order": 99, "picks": []}
        lvl, note = None, None
        for raw in body.splitlines():
            line = raw.strip()
            if not line:
                continue
            m = re.match(r"^#(\w+)\s*(.*)$", line)
            if m:
                k, v = m.group(1).lower(), m.group(2).strip()
                if k == "name":
                    g["name"] = v
                elif k == "minlevel":
                    g["min"] = int(v)
                elif k == "maxlevel":
                    g["max"] = int(v)
                elif k == "hardcore":
                    g["hc"] = True
                elif k == "order":
                    g["order"] = int(v)
                elif k == "next":
                    g["next"] = v
                continue
            m = re.match(r"^level\b\s*(?:--\s*(.*))?$", line)
            if m:
                lvl = g["min"] if lvl is None else lvl + 1
                note = (m.group(1) or "").strip()
                continue
            m = re.match(r"^\.talent\s+(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)", line)
            if m and lvl is not None:
                tab, row, col, rank = (int(x) for x in m.groups())
                g["picks"].append({"lvl": lvl, "tab": tab, "row": row, "col": col, "rank": rank, "note": note})
        if g["name"] and g["picks"]:
            guides.append(g)
    return guides


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("rxp")
    ap.add_argument("--out", default=os.path.join("ZugzugLeveler", "data", "Talents.lua"))
    a = ap.parse_args(argv)
    try:
        commit = subprocess.run(["git", "-C", a.rxp, "rev-parse", "HEAD"], capture_output=True, text=True, check=True).stdout.strip()[:10]
    except (OSError, subprocess.CalledProcessError):
        commit = "unknown"
    out = [
        "-- Talents.lua -- generated by tools/rxptalents.py; do not edit by hand, re-run the tool.",
        "--",
        "-- Adapted from RestedXP Guides' talent guides, https://github.com/RestedXP/RXPGuides",
        "-- (commit %s): Guides/Talents/classic-*.lua." % commit,
        "-- Licensed CC BY-NC-SA 4.0, https://creativecommons.org/licenses/by-nc-sa/4.0/",
        "-- Changes: converted to a Lua table; pet talents left out.",
        "-- Personal, non-commercial use only. Credit: RestedXP.",
        "",
        "local _, ns = ...",
        "ns.TalentData = {",
    ]
    total = 0
    for cls in CLASSES:
        path = os.path.join(a.rxp, "Guides", "Talents", "classic-%s.lua" % cls)
        if not os.path.exists(path):
            continue
        with open(path, encoding="utf-8") as f:
            guides = parse(f.read())
        out.append("  %s = {" % cls.upper())
        for g in guides:
            picks = ", ".join("{ %d, %d, %d, %d, %d, %s }" % (p["lvl"], p["tab"], p["row"], p["col"], p["rank"], lua(p["note"]))
                              for p in g["picks"])
            out.append("    { name = %s, min = %d, max = %d, hc = %s, order = %d%s, picks = { %s } }," % (
                lua(g["name"]), g["min"], g["max"], lua(g["hc"]), g["order"],
                (", next = " + lua(g["next"])) if g.get("next") else "", picks))
            total += 1
        out.append("  },")
    out += ["}", ""]
    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    with open(a.out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))
    print("wrote %s: %d talent guides" % (a.out, total))


if __name__ == "__main__":
    main()
