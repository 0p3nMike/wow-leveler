-- plg_professions.lua -- ProfessionLevelingGuide's data -> SlopLeveler/data/Professions.lua
--
--   luajit tools/plg_professions.lua <ProfessionLevelingGuide clone> [out file]
--
-- ProfessionLevelingGuide (https://github.com/icewrange/ProfessionLevelingGuide)
-- is MIT-licensed (Copyright (c) 2026 icêheal); its LICENSE text is copied into
-- the output's header as the license asks. Its own notes say the facts were
-- checked against Wowhead Classic / Icy Veins / wow-professions.com, so treat
-- them as a plan to verify in game, which the addon does: in the profession
-- window it reads the game's own skill-up colours.
--
-- The data files are plain Lua tables, so this loads them the way the addon
-- does (English locale) and writes our shape:
--   guides[Profession] = { { lo, hi, n = count, item = name, mats = {{n, name}...} }
--                          | { lo, hi, gather = "Copper Ore", a = zones, h = zones, both = zones, hint } }
--   trainers[Profession] = { { rank = "...", where = "...", a = {map, x, y}, h = {map, x, y} } }
--   items[lower name] = itemID   (from Daten_IDs.lua "i:<id>" entries)

local dir, out = arg[1], arg[2] or "SlopLeveler/data/Professions.lua"
assert(dir, "usage: luajit tools/plg_professions.lua <ProfessionLevelingGuide dir> [out]")

-- German keys in the data -> English names (Core/BSG_Berufe.lua's own table)
local EN = {
  ["Alchimie"] = "Alchemy", ["Schmiedekunst"] = "Blacksmithing", ["Ingenieurskunst"] = "Engineering",
  ["Lederverarbeitung"] = "Leatherworking", ["Schneidern"] = "Tailoring", ["Verzauberkunst"] = "Enchanting",
  ["Kochkunst"] = "Cooking", ["Erste Hilfe"] = "First Aid", ["Bergbau"] = "Mining",
  ["Kräuterkunde"] = "Herbalism", ["Kürschnerei"] = "Skinning", ["Angeln"] = "Fishing",
}

-- the environment the data files expect
GetLocale = function() return "enUS" end
BerufeGuideDB, BerufeLehrerDB = {}, {}
local function load(rel)
  local f = assert(loadfile(dir .. "/" .. rel))
  f("BerufeSkillGuide", {})
end
for _, p in ipairs({ "Alchimie", "ErsteHilfe", "Ingenieurskunst", "Kochen", "Lederverarbeitung",
    "Sammelberufe", "Schmiedekunst", "Schneidern", "Verzauberkunst" }) do
  load("Data/Classic/Guides/Daten_" .. p .. "_EN.lua")
end
load("Data/Classic/Lehrer/Daten_Lehrer_EN.lua")
load("Data/Classic/Lehrer/Daten_Lehrer_Zusatz_EN.lua")

-- name -> itemID, from the search-name table ("i:<id>")
local items = {}
local idsrc = assert(io.open(dir .. "/Data/Allgemein/Daten_IDs.lua")):read("*a")
for name, id in idsrc:gmatch('T%["([^"]+)"%]%s*=%s*"i:(%d+)"') do items[name:lower()] = tonumber(id) end
-- ...and the materials table (Daten_Items.lua: DB["Linen Cloth"] = 2589)
local itemsrc = assert(io.open(dir .. "/Data/Allgemein/Daten_Items.lua")):read("*a")
for name, id in itemsrc:gmatch('DB%["([^"]+)"%]%s*=%s*(%d+)') do items[name:lower()] = tonumber(id) end

local function count(s) -- "95 Bolt of Linen Cloth" -> 95, "Bolt of Linen Cloth"
  local n, name = (s or ""):match("^%s*[^%d]*(%d+)%s+(.-)%s*$")
  return tonumber(n), name or s
end

local function mats(s)
  local t = {}
  for part in (s or ""):gmatch("[^,]+") do
    local n, name = count(part)
    if n and name and name ~= "" then t[#t + 1] = { n, name } end
  end
  return t
end

local function q(s) return string.format("%q", s) end
local function zone(m, x, y) return (m and x) and ("{ %d, %.4f, %.4f }"):format(m, x / 100, y / 100) or "nil" end

local lines = {
  "-- data/Professions.lua -- generated by tools/plg_professions.lua; re-run the tool, do not edit.",
  "--",
  "-- From ProfessionLevelingGuide, https://github.com/icewrange/ProfessionLevelingGuide",
  "-- (classic 1-300 guides, trainers, item IDs; English). Its license:",
  "--",
}
for l in (assert(io.open(dir .. "/LICENSE.txt")):read("*a")):gmatch("[^\n]*") do
  lines[#lines + 1] = "--   " .. l:gsub("\r", "")
end
lines[#lines + 1] = ""
lines[#lines + 1] = "local _, ns = ..."
lines[#lines + 1] = ""
lines[#lines + 1] = "ns.ProfData = { guides = {"

local nsteps = 0
for de, steps in pairs(BerufeGuideDB) do
  local en = EN[de]
  if en then
    lines[#lines + 1] = ("  [%s] = {"):format(q(en))
    for _, s in ipairs(steps) do
      nsteps = nsteps + 1
      if s.typ == "sammeln" then
        lines[#lines + 1] = ("    { %d, %d, gather = %s, a = %s, h = %s, both = %s, hint = %s },"):format(
          s.minSkill, s.maxSkill, q(s.item or ""), s.allianz and q(s.allianz) or "nil",
          s.horde and q(s.horde) or "nil", s.beide and q(s.beide) or "nil", s.hinweis and q(s.hinweis) or "nil")
      else
        local n, name = count(s.item)
        local m = {}
        for _, mt in ipairs(mats(s.mats)) do m[#m + 1] = ("{ %d, %s }"):format(mt[1], q(mt[2])) end
        lines[#lines + 1] = ("    { %d, %d, n = %s, item = %s, mats = { %s } },"):format(
          s.minSkill, s.maxSkill, n or "nil", q(name or ""), table.concat(m, ", "))
      end
    end
    lines[#lines + 1] = "  },"
  end
end
lines[#lines + 1] = "}, trainers = {"
for de, tiers in pairs(BerufeLehrerDB) do
  local en = EN[de]
  if en then
    lines[#lines + 1] = ("  [%s] = {"):format(q(en))
    for _, t in ipairs(tiers) do
      lines[#lines + 1] = ("    { rank = %s, where = %s, a = %s, h = %s },"):format(
        q(t.stufe or ""), q((t.standorte or ""):gsub("\n", " · ")),
        zone(t.allianzZone, t.allianzX, t.allianzY), zone(t.hordeZone, t.hordeX, t.hordeY))
    end
    lines[#lines + 1] = "  },"
  end
end
lines[#lines + 1] = "}, items = {"
local names = {}
for name in pairs(items) do names[#names + 1] = name end
table.sort(names)
for _, name in ipairs(names) do lines[#lines + 1] = ("  [%s] = %d,"):format(q(name), items[name]) end
lines[#lines + 1] = "} }"
lines[#lines + 1] = ""

local f = assert(io.open(out, "wb"))
f:write(table.concat(lines, "\n"))
f:close()
print(("wrote %s: %d steps, %d trainer professions, %d item ids"):format(out, nsteps,
  (function() local n = 0; for k in pairs(BerufeLehrerDB) do if EN[k] then n = n + 1 end end; return n end)(), #names))
